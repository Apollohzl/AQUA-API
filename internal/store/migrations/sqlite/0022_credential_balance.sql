-- 迁移 0022：上游凭据的「余额」维度
--
-- 背景：
--   部分上游（OpenAI 兼容形态）按"每把密钥一个余额"发放额度
--   （例如同一批申请的密钥分别为 49 / 62 / 95 / 55 …）。
--   这些密钥一旦把额度用光，继续把请求发给它只会白白浪费一次尝试
--   （多为 402/429），却不会让渠道整体更快失败。运营上需要能"录入每把密钥的余额，
--   并在余额耗尽时让它自动退出调度"，把流量集中到还有余额的密钥上。
--
-- 设计说明（重要，务必读）：
--   1) balance 的取值语义：
--        -1  = 余额未知（默认值，也是"未录入"）；
--        >=0 = 已知余额，0 表示"已知且已用尽"。
--      【关键】默认值必须是 -1 而不是 0：0 表示"已用尽"，
--      若默认写成 0，升级后所有既有密钥会被系统判定为余额耗尽而集体退出调度，
--      直接造成线上事故。默认 -1（未知）则对所有既有密钥"不做任何约束"，行为不变。
--   2) 余额单位与上游一致（整数，不换算、不乘 100）：上游怎么显示就怎么录，
--      避免引入"分/元"之类的换算歧义。
--   3) 余额由站长人工维护，网关【不自动扣减】：
--      网关无法得知上游的真实扣费（上游可能按 token、按次、按模型分别计价，
--      且第三方代理会在中间二次计费），自动扣减只会产生与上游对不上的假数字。
--      因此本列只用于"已知耗尽时不再把请求浪费在这把密钥上"，不参与任何计费计算。
--   4) balance_updated_at 记录余额被人工更新的时间（Unix 秒，0 表示未录入）。
--      它让后台可以展示"这个余额数字是什么时候录的"，帮助判断是否已过时。
--
-- 兼容性：
--   SQLite 的 ADD COLUMN 必须给出默认值；两列都有默认值，
--   既有数据的语义完全不变（余额未知 = 不受余额约束）。
--   本迁移只加列、不改动任何既有列与索引。

-- 凭据余额：-1=未知（不受约束），>=0=已知余额（0 表示已用尽，退出调度）
ALTER TABLE channel_keys ADD COLUMN balance INTEGER NOT NULL DEFAULT -1;

-- 余额被人工更新的时间（Unix 秒）：0 表示从未录入过余额
ALTER TABLE channel_keys ADD COLUMN balance_updated_at INTEGER NOT NULL DEFAULT 0;
