-- 迁移 0042：用户增加「代理分组」
--
-- 意图（Why）：
--   站主要做代理生意：代理从本站按折扣拿货，再对外加价售卖。
--   已有的两块积木（0034 充值门槛、0039 仅后台分发）解决的只是"令牌能不能
--   挂到某个分组上"，解决不了"这个人打开模型广场时，看到的应该是哪一套模型与价格"。
--
--   不加本列的话，只有两种选择，都不对：
--     1) 广场对所有人展示同一套公共模型与公共价 —— 代理看不到自己的批发模型，
--        也看不到"原价 vs 代理价"的对比，等于白做；
--     2) 把批发分组直接放到公开广场 —— 等于向全网公示批发折扣，价格体系立刻失守。
--
--   本列把"这个用户属于哪个定价分组"变成用户自身的属性：广场按查看者的
--   agent_group 决定展示哪一套模型清单与价格，非代理（空串）维持现状。
--
-- 取值语义：
--   ''      = 普通用户（默认，也是全部历史数据的取值）。广场行为与迁移前逐字一致：
--             展示公共分组下的模型与价格。
--   'xxx'   = 代理用户，其查看广场时使用的分组名（对应 model_groups.name）。
--             广场只展示该分组下的模型，并同时给出「原价」（公共价）与
--             「代理价」（该分组倍率折算后的价格），前端渲染成"原价划线 + 折扣块"。
--
--   为什么按【分组名】而不是加一个布尔 is_agent：
--     折扣的落地方式在现有系统里已经统一为"分组的计费倍率 ratio"
--     （billing.ApplyRatio：最终额度 = 基础额度 × ratio / 100）。
--     存分组名 = 直接复用这条既有链路，改折扣只需改分组倍率一处，
--     不必在用户表另起一套折扣字段，也就不会出现"用户折扣与分组倍率打架"。
--
--   为什么放在 users 而不是单开一张授权表：
--     当前需求是"一个代理对应一个分组"（站主明确只安排一个战略代理）。
--     单列即可完整表达，且无需引入新的仓储与联表查询。若后续要做
--     "一人多分组 / 多级代理 / 授权历史"，再升级为 agent_assignments 表
--     （见 docs/22-代理分组与拿货折扣方案.md 的 M2 阶段），届时本列可作为
--     迁移来源，不会白写。
--
-- 兼容性：
--   只加列、不改既有列，默认 ''（普通用户）保证升级后既有用户行为逐字不变。
--   取值本身是【运营数据】（由管理员在后台用户页填写），不写进迁移。
--
-- 流转（Flow）：
--   users.agent_group
--     → model.User.AgentGroup
--     → server.handleModelPlaza：按查看者分组过滤模型并按该分组倍率出价
--     → 前端模型广场：代理视图（原价划线 + 橙色折扣块）
--
-- 扩展（Extend）：
--   若要支持"一人多分组"，把本列升级为关联表并在 plaza 处改为"取第一个生效授权"，
--   其余链路（分组倍率、价格表）无需改动。

ALTER TABLE users ADD COLUMN agent_group TEXT NOT NULL DEFAULT '';
