-- 迁移 0025：渠道支持属于【多个分组】
--
-- 背景（为什么必须支持多分组）：
--   此前一个渠道只能属于一个分组（channels.group_name），路由时按令牌的分组精确匹配。
--   这在"一个上游只服务一类用户"时够用，但真实运营里经常需要：
--     · 同一个上游同时服务免费用户与付费用户（免费分组 + 自营分组）；
--     · 上线新分组时先让老渠道覆盖过去，避免"新分组下没有任何渠道"导致整组 503；
--     · 把一个渠道整体开放给若干个用户分组（如"内部组 + 测试组"）。
--   只能选一个分组的直接后果就是：用户拿着默认分组的令牌调用只挂在另一个分组上的
--   模型时，网关在选渠道阶段就找不到候选，返回 0ms 的 503——线上已实测到这种大面积 503。
--
-- 设计说明（重要）：
--   1) 新增 group_names 存【逗号分隔的分组清单】，是路由匹配的唯一依据；
--   2) 保留 group_name 作为"主分组"（= 清单里的第一个），继续承担：
--        展示、分组引用统计、模型广场归属等既有用途；
--     这样既不必改动所有读取 group_name 的旧代码，也不会出现两套真相互相矛盾——
--      写入时由仓储保证 group_name 恒等于 group_names 的第一项。
--   3) 空串表示"未显式配置"，读取时回退为 [group_name]，因此既有数据行为完全不变。
--   4) 匹配语义：请求分组 ∈ 渠道分组清单 即可路由（见 store 的 buildChannelWhere）。
--
-- 兼容性：只加列、给默认值；既有渠道升级后清单为空 → 回退单分组，行为与升级前一致。

ALTER TABLE channels ADD COLUMN group_names TEXT NOT NULL DEFAULT '';
