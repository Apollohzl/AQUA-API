-- 迁移 0024：渠道级「密钥失败策略」
--
-- 背景（为什么必须做成可配置）：
--   现行实现对所有渠道只有一套策略——凭据连续失败达到阈值（或上游响应里出现
--   "revoked / invalid api key" 之类措辞）就【自动摘除】。这在"密钥确实会死"的
--   上游（付费账号被停用、密钥被吊销）是合理的，但对另一些上游是错的：
--     例如 NVIDIA NIM 的免费密钥池，密钥本身不会"死亡"，
--     失败几乎都来自上游限流、瞬时 5xx 或临时风控；一旦被自动摘除，
--     整个池子会随时间被"误杀"到没有可用密钥——表现就是用户侧大面积 503。
--   运营上需要能按渠道选择：
--     cooldown_only ——【只冷却，永不自动摘除】：失败后进冷却池，到期自动回到调度；
--                       只有站长手动下架才会退出（默认值）。
--     auto_remove   ——【保留自动摘除】：连续失败达阈值/上游明确判定永久无效时摘除，
--                       适合"密钥真的会死"的上游。
--
-- 另一项 key_cooldown_seconds 让站长自己决定"进冷却池多久"：
--   0（默认）= 使用内置的分级指数退避（限流 30s 起、5xx 15s 起、鉴权失败 30min）；
--   >0       = 所有凭据级失败统一冷却该秒数（可预测、易解释，适合自营固定池）。
--
-- 兼容性（重要）：
--   默认值为 'cooldown_only'，即升级后既有渠道不再自动摘除密钥。
--   这是一个【有意为之的行为变更】：自动摘除造成的池子萎缩已被证实会造成
--   大面积 503（误杀好密钥），代价远大于"偶发多试一把失效密钥"。
--   仍需要自动摘除的站长，在渠道编辑里把策略改成 auto_remove 即可。
--   两列都有默认值，既有数据语义明确，不需要额外回填。

ALTER TABLE channels ADD COLUMN key_failure_policy TEXT NOT NULL DEFAULT 'cooldown_only';

ALTER TABLE channels ADD COLUMN key_cooldown_seconds INTEGER NOT NULL DEFAULT 0;
