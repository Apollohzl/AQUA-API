-- 迁移 0036：用户邮箱唯一（去重 + 部分唯一索引）
--
-- 意图（Why）：
--   本站邮箱有三个真实用途：注册验证码、通知/群发、找回联系。
--   此前 users.email 只是一个普通列（见 0003_site.sql：email TEXT NOT NULL DEFAULT ''），
--   既没有唯一约束、注册与后台建号也不做占用校验，导致「同一个邮箱绑定了多个账号」：
--     1) 一个邮箱本应代表"一个真实的人"，重复绑定等于把同一个人拆成多个账号，
--        运营发福利、发通知都会重复投递，额度也会被同一人重复领取；
--     2) 后续任何"按邮箱唯一定位用户"的功能（邮箱登录、邮箱找回）都无法实现——
--        查到两行时无从判断该给谁。
--   因此本次把"一个邮箱只能绑定一个账号"落到数据库层面，而不是只在前端/接口里
--   做一次"先查后写"——那在并发下必然漏（两个请求同时查、都没查到、都写入）。
--
-- 设计说明（与 0021 的 invite_code 同套路）：
--   1) 唯一索引【必须是部分索引】(WHERE email <> '')：
--      邮箱是【可选】字段，未填写的用户 email 均为空串。若建普通唯一索引，
--      这些空串会互相冲突，导致迁移直接失败。部分索引只约束"非空邮箱"，
--      从而允许"未绑定邮箱"的用户大量共存。
--   2) 建索引前必须先【去重】，否则索引创建会因存量重复而失败：
--      每个重复邮箱只保留 id 最小的那一行（= 最早注册的账号，通常也是用户本人），
--      其余行的邮箱清空为空串（不删账号！账号下的令牌与额度必须原样保留，
--      邮箱只是可再补录的联系方式）。
--   3) 去重前先做一次归一化（TRIM + LOWER）：
--      注册链路用 model.NormalizeEmail 统一小写，但后台建号/改号此前只做了 TRIM，
--      存量数据里可能存在大小写不同的"同一个邮箱"。若不归一化，
--      唯一索引会被 'A@x.com' 与 'a@x.com' 绕过，等于没做。
--
-- 兼容性：
--   全部为数据修正与索引创建，不改表结构；空串邮箱不参与唯一约束，
--   因此"未填邮箱"的用户不受任何影响。
--   TRIM/LOWER 均为 SQLite 内置函数，无需额外扩展。

-- 第一步：归一化存量邮箱（去空白 + 转小写），与 model.NormalizeEmail 保持同一口径。
UPDATE users SET email = LOWER(TRIM(email)) WHERE email <> '';

-- 第二步：清理重复邮箱 —— 每个邮箱只保留 id 最小（最早注册）的账号，其余清空。
UPDATE users SET email = ''
WHERE email <> ''
  AND id NOT IN (
      SELECT MIN(id) FROM users WHERE email <> '' GROUP BY email
  );

-- 第三步：建部分唯一索引 —— 从此"一个邮箱只能绑定一个账号"由数据库兜底。
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email ON users (email) WHERE email <> '';
