-- 迁移 0039：模型分组增加「仅后台可用」标记
--
-- 意图（Why）：
--   `unlock_min_recharge_cents`（迁移 0034）能表达"充够钱自动解锁"，
--   但表达不了"谁都别想自助拿到，只有后台代建令牌才行"。
--
--   后者正是**批发价分组**（如"代理拿货"）唯一正确的落地方式：
--   批发价一旦被普通用户自助拿到，整个价格体系就塌了；而设一个很高的充值门槛
--   又会让"想按量拿货的小代理"被挡在门外（站长明确否掉了"累计充值满 1000 元"）。
--
--   因此把"这个分组只能由管理员分发"变成数据。
--
-- 取值语义：
--   0 = 不限制（默认，也是全部历史数据的取值）：与迁移前行为逐字一致，
--       用户可以在门户自选该分组（仍受 0034 的充值门槛约束）。
--   1 = 仅后台：门户的可选分组列表不下发该分组；非管理员即使绕过界面
--       直接用接口指定它也会被拒；管理员在后台"代客户建令牌"不受限制。
--
-- 判据为什么是【发起请求的人】而不是【令牌归属者】：
--   后台代建令牌传的是**目标用户**的 user_id（见 handler_admin.go 的
--   handleAdminCreateToken）。若按归属者判定，代理令牌在后台也建不出来——
--   功能等于废掉。因此校验点取"当前请求用户是否管理员"。
--
-- 与 0034 的组合语义（两个字段互不冲突，同时成立时前者优先拦截）：
--   admin_only=1                    → 只看"发起人是不是管理员"
--   admin_only=0 且 门槛 > 0        → 只看"归属用户累计充值是否达标"
--
-- 兼容性：
--   只加列、不改既有列，默认 0（不限制）保证升级后既有分组行为逐字不变。
--
-- 流转（Flow）：
--   model_groups.admin_only
--     → ModelGroup.AdminOnly
--     → server.resolveTokenGroupName：仅后台分组对非管理员返回 403
--     → 门户分组下拉（/api/user/groups）直接不下发该分组
--
-- 扩展（Extend）：
--   若将来还需要"仅某类用户"（如仅企业账号），在 ModelGroup 上加条件字段即可，
--   校验点仍集中在 resolveTokenGroupName 一处。

ALTER TABLE model_groups ADD COLUMN admin_only INTEGER NOT NULL DEFAULT 0;
