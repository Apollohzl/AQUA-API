-- 迁移 0034：模型分组增加「充值解锁门槛」
--
-- 意图（Why）：
--   分组倍率是本网关的定价杠杆（倍率 50 = 收标价的 5 折）。此前"低价分组
--   只给大客户"这件事只写在分组描述里靠人自觉，而令牌分组是【用户自选】的：
--   任何用户都能把令牌挂到 5 折分组上，折扣立刻生效，站长被无声地吃掉毛利。
--
--   本列把"这个分组要够格才能用"变成数据，由服务端在【分配分组时】强制校验：
--   累计有效充值未达阈值 → 拒绝把令牌挂到该分组，前端也只允许在已解锁时选择。
--
-- 取值语义：
--   0     = 无门槛（默认，也是全部历史数据的取值）：任何用户都可选该分组，
--           与迁移前的行为完全一致（不会因为升级而突然锁死既有分组）。
--   > 0   = 解锁所需的最低【累计有效充值金额】，单位：分。
--           例如 10000 = 需累计充值满 100 元。
--
--   为什么门槛用"累计充值金额（分）"而不是"账户余额额度（quota）"：
--     1) 余额会被消费掉——用户充 100 元用掉 60 元后余额只剩 40 元，
--        按余额算会凭空失去资格，与"充值满 100 元解锁"的承诺不符；
--     2) 额度是本项目的【内部记账单位】，其数值随兑换比例（settings 的
--        payment_exchange_rate）变动，用它做业务门槛会在改比例时集体失效；
--        金额（分）是外部事实，与内部刻度无关。
--
-- 兼容性：
--   只加列、不改既有列，默认 0（无门槛）保证升级后既有分组行为逐字不变。
--   阈值本身属于【运营数据】，不写进迁移（各站点定价策略不同），
--   由管理员在后台分组页填写，或由部署脚本按站点设置。
--
-- 流转（Flow）：
--   model_groups.unlock_min_recharge_cents
--     → ModelGroup.UnlockMinRechargeCents
--     → server.resolveTokenGroupName：合并"累计已付金额"判断是否放行
--     → 门户分组下拉（/api/user/groups）按 unlocked 置灰
--
-- 扩展（Extend）：
--   若将来门槛要按"单个订单金额""近 N 天充值"等更复杂口径判定，
--   在 ModelGroup 上加条件字段即可，校验点仍集中在 resolveTokenGroupName 一处。

ALTER TABLE model_groups ADD COLUMN unlock_min_recharge_cents INTEGER NOT NULL DEFAULT 0;
